#!/usr/bin/env node
// Writes .env.local from the running local Supabase (`supabase start`) + sane defaults.
// Usage: pnpm env:local [--force]
import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const target = resolve(root, '.env.local');
const force = process.argv.includes('--force');

if (existsSync(target) && !force) {
  console.log('.env.local already exists. Use --force to overwrite.');
  process.exit(0);
}

let out;
try {
  out = execSync('supabase status -o env', {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch {
  console.error('Could not read `supabase status`. Is local Supabase running? Try: pnpm db:start');
  process.exit(1);
}

const vars = {};
for (const line of out.split(/\r?\n/)) {
  const m = line.match(/^([A-Z_]+)="?(.*?)"?$/);
  if (m) vars[m[1]] = m[2];
}

for (const k of ['API_URL', 'ANON_KEY', 'SERVICE_ROLE_KEY', 'DB_URL']) {
  if (!vars[k]) {
    console.error(`Missing ${k} in supabase status output.`);
    process.exit(1);
  }
}

const content = `# Generated by scripts/setup-local-env.mjs (local development only)
APP_URL=http://localhost:3000
NODE_ENV=development
SETTINGS_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}

NEXT_PUBLIC_SUPABASE_URL=${vars.API_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${vars.ANON_KEY}
SUPABASE_SERVICE_ROLE_KEY=${vars.SERVICE_ROLE_KEY}
SUPABASE_DB_URL=${vars.DB_URL}

REDIS_URL=redis://localhost:6379

AI_MODE=mock
OPENROUTER_API_KEY=
OPENROUTER_TEXT_MODEL=deepseek/deepseek-v4.1-flash-1017
REPLICATE_API_TOKEN=
REPLICATE_IMAGE_MODEL=openai/gpt-image-2
REPLICATE_IMAGE_QUALITY=low
REPLICATE_TTS_MODEL=jaaari/kokoro-82m

WORKER_QUEUES=text,image,export,audio,system
WORKER_TEXT_CONCURRENCY=50
WORKER_IMAGE_CONCURRENCY=5
WORKER_EXPORT_CONCURRENCY=2
WORKER_AUDIO_CONCURRENCY=3
OPENROUTER_RPM=300
REPLICATE_RPM=120
`;

writeFileSync(target, content);
console.log(`Wrote ${target}`);
